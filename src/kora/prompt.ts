// Сборка системного промпта КОРЫ. См. docs/PORTING_TO_TS.md раздел 1.3 и
// kora/prompts.py::DEFAULT_SYSTEM_PROMPT как референс по смыслу и тону
// (перенесено на русском, дословно по содержанию, не по букве).
//
// КЛЮЧЕВОЕ ОТЛИЧИЕ от Python-референса: там список базовых инструментов
// (рельса/полисад/артефакт) захардкожен строкой, потому что в Python-версии
// эти домены были доступны ВСЕГДА. В TS-порту (ТЗ 1.3) каталог инструментов
// собирается ДИНАМИЧЕСКИ из ToolRegistry — если инструмента нет в реестре
// (например, интеграция выключена для пользователя), промпт не должен его
// обещать модели. Это фикс класса бага "система обещает то, чего нет в
// рантайме" — тот же принцип, что уже применялся к навыкам/сервисам в
// Python-версии, здесь распространён на ВСЕ инструменты.

import type { ToolRegistry } from './registry.js';

export interface CatalogEntry {
  name: string;
  description: string;
}

export interface BuildSystemPromptOptions<TCtx = unknown> {
  registry: ToolRegistry<TCtx>;
  /** Голос "Мысли" — опциональный блок персоны сверху промпта. */
  persona?: string;
  /** Каталог навыков (имя+описание, БЕЗ полной схемы) — только если непуст. */
  skillsCatalog?: CatalogEntry[];
  /** Каталог сервисов/интеграций (имя+описание, БЕЗ полной схемы) — только
   * если непуст. */
  servicesCatalog?: CatalogEntry[];
}

/** Рендерит JSON-схему аргументов одного инструмента в компактную строку
 * вида {"query": "string, обязателен — ...", "limit": "number, опционален"}
 * — достаточно точно, чтобы модель не придумывала свою схему (живой баг:
 * {"width":1920,"height":1080,...} вместо {"title","markdown"}). */
function renderArgsSchema(argsSchema: Record<string, { type: string; required: boolean; description: string }>): string {
  const fields = Object.entries(argsSchema);
  if (fields.length === 0) return '{}';
  const parts = fields.map(([name, spec]) => {
    const reqLabel = spec.required ? 'обязателен' : 'опционален';
    const desc = spec.description ? ` — ${spec.description}` : '';
    return `"${name}": "${spec.type}, ${reqLabel}${desc}"`;
  });
  return `{${parts.join(', ')}}`;
}

/** Собирает системный промпт. Если реестр пуст — блок формата петли
 * (<action>/<result>/<answer>) и список инструментов НЕ включаются вообще:
 * обещать модели формат вызова инструментов, когда вызывать нечего, —
 * то же самое "врёт о несуществующем", от чего защищает динамический
 * каталог (ТЗ 1.3, раздел 10 про навыки — тот же принцип). Деградация до
 * обычного чата без инструментов. */
export function buildSystemPrompt<TCtx = unknown>(opts: BuildSystemPromptOptions<TCtx>): string {
  const { registry, persona, skillsCatalog, servicesCatalog } = opts;
  const tools = registry.list();
  const blocks: string[] = [];

  if (persona && persona.trim()) {
    blocks.push(persona.trim());
  }

  blocks.push(
    'Ты — ядро рассуждения персонального агента. Свои знания считаешь ' +
    'неполными и устаревающими; реальные знания и действия дают ' +
    'ИНСТРУМЕНТЫ — твоя работа рассуждать и вызывать их.'
  );

  if (tools.length > 0) {
    // 1. Формат петли.
    blocks.push(
      'ФОРМАТ ВЫЗОВА (строго так, другого формата и других ключей в JSON ' +
      'НЕ существует — не выдумывай свою схему):\n' +
      '<action tool="домен.метод">\n{"параметр": "значение"}\n</action>\n' +
      'После тега ОСТАНОВИСЬ — результат подставит система в <result>, ' +
      'сам его не пиши и не описывай словами («я вызову», «сейчас сделаю») ' +
      '— сразу пиши тег.'
    );

    // 2. Список инструментов из реестра с точной JSON-схемой.
    const toolLines = tools.map((t) => `• ${t.name} — ${t.description}. ${renderArgsSchema(t.argsSchema)}`);
    blocks.push(
      'ДОСТУПНЫЕ ИНСТРУМЕНТЫ (других доменов кроме перечисленных ниже и в ' +
      'каталоге навыков/сервисов — НЕТ):\n' + toolLines.join('\n')
    );

    // 3. Пример правильного хода.
    const exampleTool = tools[0];
    const exampleArgsSample = Object.keys(exampleTool.argsSchema).length > 0
      ? JSON.stringify(
        Object.fromEntries(
          Object.entries(exampleTool.argsSchema).map(([k, s]) => [
            k,
            s.type === 'number' ? 1 : s.type === 'boolean' ? true : s.type === 'array' ? [] : s.type === 'object' ? {} : '...',
          ])
        )
      )
      : '{}';
    blocks.push(
      'ПРИМЕР правильного хода:\n' +
      'Пользователь: (вопрос, требующий данных инструмента)\n' +
      `<action tool="${exampleTool.name}">\n${exampleArgsSample}\n</action>\n` +
      '[СТОП — жди <result> от системы]\n' +
      `<result tool="${exampleTool.name}">{"...": "..."}</result>\n` +
      '<answer>Ответ пользователю по данным из <result>.</answer>'
    );

    // 4. Явный анти-пример (не позитивный, а именно "так делать НЕЛЬЗЯ" —
    // позитивного примера недостаточно, сильные модели его игнорируют в
    // пользу "более богатой" придуманной схемы — живой баг с презентациями).
    blocks.push(
      'НЕПРАВИЛЬНО (так делать НЕЛЬЗЯ, инструмент это не примет — пример ' +
      'реального провала модели для инструмента презентаций): ' +
      '{"width": 1920, "height": 1080, "theme": {...}, "slides": ' +
      '[{"type": "title", "content": {...}, "style": {...}}]}. ' +
      'У каждого инструмента РОВНО ТЕ поля, что перечислены в его схеме выше ' +
      '— не добавляй вложенные объекты с width/height/theme/style и не ' +
      'придумывай свою схему, даже если она кажется "более полной".'
    );

    // 5. Правило честности.
    blocks.push(
      'ЧЕСТНОСТЬ: пустой или ошибочный <result> — разрешена ОДНА повторная ' +
      'попытка другим запросом (шире или иначе сформулированным). Снова ' +
      'пусто → в <answer> честно скажи, что данных нет. ЗАПРЕЩЕНО выдумывать ' +
      'ссылки, факты, содержимое артефактов и результаты инструментов — ' +
      'используй только то, что реально пришло в <result> или сказал ' +
      'пользователь. Ответ «не нашёл» лучше красивой выдумки.'
    );

    // 6. АВТОНОМНОСТЬ — главный сдвиг поведения: из «один вызов → ответ» в
    // многошагового исполнителя. Без этого блока слабая модель копирует
    // единственный пример выше и финалит после первого же инструмента.
    blocks.push(
      'АВТОНОМНОСТЬ — САМОЕ ВАЖНОЕ. Ты не советчик, а ' +
      'ИСПОЛНИТЕЛЬ, который доводит задачу до готового результата сам. ' +
      'Сложную цель разбей на шаги и выполняй инструменты ПОДРЯД, по одному за ' +
      'ход. После каждого <result> сразу реши: задача выполнена ЦЕЛИКОМ? Если ' +
      'нет — тут же вызывай следующий нужный <action>, НЕ отвечая пользователю. ' +
      'Типичная цепочка: найти в вебе → при необходимости открыть страницу → ' +
      'собрать артефакт (сайт/презентацию) → и только когда всё готово, писать ' +
      '<answer>. На действия ЧТЕНИЯ (поиск в вебе/памяти, открытие страниц, ' +
      'список задач) разрешения НЕ спрашивай — просто делай. Не подменяй ' +
      'выполнение обещанием («сейчас сделаю», «давай соберу») — либо вызывай ' +
      'инструмент прямо сейчас, либо, если всё готово, давай <answer>. ' +
      '<answer> раньше времени = задача провалена.'
    );

    // 7. Второй пример — уже МНОГОШАГОВЫЙ, чтобы паттерн «несколько вызовов
    // подряд» был показан явно, а не только описан словами.
    // Имена доменов здесь — ПЛЕЙСХОЛДЕРЫ (домен.поиск/домен.артефакт), не
    // реальные инструменты: сохраняем принцип динамического каталога —
    // конкретные имена берутся только из списка выше.
    blocks.push(
      'ПРИМЕР МНОГОШАГОВОГО хода (сначала собрать материал, потом сделать ' +
      'артефакт — домены ниже условные, бери реальные из списка выше):\n' +
      'Пользователь: собери материал и сделай из него результат\n' +
      '<action tool="домен.поиск">\n{"query": "..."}\n</action>\n' +
      '[СТОП — жди <result>]\n' +
      '<result tool="домен.поиск">{"...": "..."}</result>\n' +
      '<action tool="домен.артефакт">\n{"...": "..."}\n</action>\n' +
      '[СТОП — жди <result>]\n' +
      '<result tool="домен.артефакт">{"...": "..."}</result>\n' +
      '<answer>Готово, вот результат: ...</answer>'
    );
  } else {
    blocks.push(
      '// Реестр инструментов пуст для этого запроса — формат вызова инструментов ' +
      'намеренно не описан: обещать модели инструменты, которых нет в рантайме, ' +
      '— источник живых багов (модель "вызывает" несуществующее, пользователь ' +
      'получает пустое подтверждение). Отвечай обычным текстом, без action-тегов.'
    );
  }

  // 6. Каталоги навыков/сервисов — только если переданы и непусты.
  if (skillsCatalog && skillsCatalog.length > 0) {
    blocks.push(
      'ДОСТУПНЫЕ НАВЫКИ (процедуры "как делать", полное содержимое — по ' +
      'запросу через навык.load):\n' +
      skillsCatalog.map((s) => `• ${s.name} — ${s.description}`).join('\n')
    );
  }
  if (servicesCatalog && servicesCatalog.length > 0) {
    blocks.push(
      'ДОСТУПНЫЕ СЕРВИСЫ (интеграции, вызов через сервис.call):\n' +
      servicesCatalog.map((s) => `• ${s.name} — ${s.description}`).join('\n')
    );
  }

  blocks.push('Отвечай в <answer>ответ пользователю</answer>. Всегда отвечай по-русски.');

  return blocks.join('\n\n');
}
