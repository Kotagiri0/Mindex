// Базовые типы ядра парсинга КОРА.
// Чистые типы, без сайд-эффектов — модуль работает на сервере, в многопользовательском контексте.

/** Распознанное действие модели, извлечённое из сырого текста ответа. */
export interface ParsedAction {
  /** Канонизированное имя инструмента (домен.метод), которым пользуется диспетчер и дедуп. */
  tool: string;
  /** Сырое имя инструмента, как его написала модель (до канонизации). */
  rawTool: string;
  /** Разобранные аргументы действия. null — если JSON не удалось восстановить даже через repairJson. */
  args: Record<string, unknown>;
  /** Сырое тело действия (то, что было между тегами или после незакрытого тега). */
  raw: string;
  /** true — действие спасено из оборванного в конце вывода тега (лимит токенов). */
  truncated: boolean;
}
