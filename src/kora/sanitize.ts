// Санитизация внешнего контента перед попаданием в контекст модели.
// См. docs/PORTING_TO_TS.md guardrails 11-12, kora/orchestrator.py::_sanitize_special.
//
// Живой баг: скрейпленная веб-страница (рельса.search/scrape_url) может
// содержать спецтокены chat-template модели (<|im_start|>, <|im_end|>,
// <|endoftext|> и т.п.) — инъекция через контент, который мы не
// контролируем. Если такой токен долетает до промпта как есть, он способен
// подделать роль в диалоге или сломать шаблон. Вырезаем ДО того, как текст
// попадёт в контекст модели (G11) и ДО того, как текст покажется
// пользователю в вопросе подтверждения write-действия (G12) — тот же
// фильтр, применённый в двух разных точках.

const SPECIAL_TOKEN_RE = /<\|[a-zA-Z_]+\|>/g;

/**
 * Вырезает спецтокены вида <|im_start|> из текста внешнего происхождения
 * (веб, документы, любой сторонний контент, который не писала сама модель
 * и не писал сам оркестратор). Заменяет на плейсхолдер — не на пустую
 * строку — чтобы в логах/тестах было видно, что вырезание произошло, а не
 * просто пропал кусок текста.
 */
export function stripSpecialTokens(text: string): string {
  if (!text) return text;
  return text.replace(SPECIAL_TOKEN_RE, '[спецтокен удалён]');
}
