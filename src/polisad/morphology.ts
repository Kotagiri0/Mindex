// ПОЛИСАД: лёгкая русская морфология для keyword-яруса. Без зависимостей.
//
// Упрощённый стеммер в духе Snowball: отрезает типовые окончания
// существительных/прилагательных/глаголов, оставляя основу ≥ 4 символов.
// «задачу», «задачи», «задачей» → «задач» — keyword-поиск перестаёт
// промахиваться из-за падежей. Основа ищется как подстрока (ILIKE %основа%).

const ENDINGS = [
  // длинные сначала — порядок важен
  'иями', 'ями', 'ами', 'иям', 'ием', 'иях',
  'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ует', 'уют', 'яет', 'яют',
  'ать', 'ять', 'еть', 'ить', 'уть', 'ешь', 'ишь', 'ете', 'ите',
  'ала', 'яла', 'ила', 'ели', 'али', 'яли', 'или',
  'ах', 'ях', 'ам', 'ям', 'ов', 'ев', 'ом', 'ем', 'ой', 'ей', 'ий', 'ый',
  'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ут', 'ют', 'ат', 'ят', 'ал', 'ял', 'ил',
  'у', 'ю', 'а', 'я', 'ы', 'и', 'е', 'о', 'ё', 'ь',
];

const MIN_STEM = 4;

export function stemRu(word: string): string {
  const w = word.toLowerCase();
  if (w.length <= MIN_STEM) return w;
  // не-кириллица (латиница, цифры) — не стеммим
  if (!/^[а-яё]+$/.test(w)) return w;
  for (const ending of ENDINGS) {
    if (w.length - ending.length >= MIN_STEM && w.endsWith(ending)) {
      return w.slice(0, w.length - ending.length);
    }
  }
  return w;
}

// Извлечение ключевых слов запроса: топ-5 слов длиннее 3 символов,
// каждое сведено к основе.
export function extractKeywords(text: string): string[] {
  return text
    .toLowerCase()
    .replace(/[^\wа-яё\s]/gi, '')
    .split(/\s+/)
    .filter(w => w.length > 3)
    .slice(0, 5)
    .map(stemRu);
}
